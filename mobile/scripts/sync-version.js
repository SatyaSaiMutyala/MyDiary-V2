#!/usr/bin/env node
/*
 * One version for the whole app.
 *
 * The source of truth is `versionName` in android/app/build.gradle. This
 * script copies it to:
 *   - src/config/appVersion.js   (what the running app compares with the store)
 *   - ios/MyDiary.xcodeproj      (MARKETING_VERSION, the iOS version)
 *
 * Gradle runs it before every Android build; run `npm run sync-version`
 * before an iOS archive. Never edit appVersion.js by hand.
 *
 * It wrote appVersion.TS until the app was converted to plain JavaScript, at which point it was
 * writing a file nothing imported: every build shipped believing it was whatever version had last
 * been typed into appVersion.js by hand. The store then looked newer for ever and the
 * "update required" box never went away. Hence the check at the end — the version it wrote is read
 * back, so a wrong path can never pass silently again.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const gradle = path.join(root, 'android/app/build.gradle');
const target = path.join(root, 'src/config/appVersion.js');
const pbxproj = path.join(root, 'ios/MyDiary.xcodeproj/project.pbxproj');

const gradleText = fs.readFileSync(gradle, 'utf8');
const name = gradleText.match(/^\s*versionName\s+"([^"]+)"/m);
const id = gradleText.match(/^\s*applicationId\s+"([^"]+)"/m);
if (!name || !id) {
  console.error('sync-version: versionName or applicationId not found in build.gradle');
  process.exit(1);
}
const version = name[1];
const packageId = id[1];

const out = `// GENERATED by scripts/sync-version.js from android/app/build.gradle.
// Do not edit: change versionName in build.gradle and build again.

export const APP_VERSION = '${version}';
export const ANDROID_PACKAGE_ID = '${packageId}';
export const PLAY_STORE_URL = \`https://play.google.com/store/apps/details?id=\${ANDROID_PACKAGE_ID}\`;
`;
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) {
  fs.writeFileSync(target, out);
  console.log(`sync-version: appVersion.js -> ${version}`);
}

// Read back what the app will actually import. If this does not say the version from
// build.gradle, the build must stop: a build that misreports its own version is the one way this
// app can lock every phone behind "update required" with no way out but a new release.
const written = fs.readFileSync(target, 'utf8').match(/APP_VERSION = '([^']+)'/);
if (!written || written[1] !== version) {
  console.error(
    `sync-version: ${path.relative(root, target)} says ` +
      `'${written ? written[1] : 'nothing'}' but build.gradle says '${version}'. ` +
      'Refusing to build: the app would not know its own version.',
  );
  process.exit(1);
}

// A leftover appVersion.ts would be imported instead of the .js on a machine whose Metro resolves
// TypeScript first — the same silent swap that caused the bug above.
const stale = path.join(root, 'src/config/appVersion.ts');
if (fs.existsSync(stale)) {
  fs.unlinkSync(stale);
  console.log('sync-version: removed the stale appVersion.ts');
}

let proj = fs.readFileSync(pbxproj, 'utf8');
const next = proj.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${version};`);
if (next !== proj) {
  fs.writeFileSync(pbxproj, next);
  console.log(`sync-version: iOS MARKETING_VERSION -> ${version}`);
}
