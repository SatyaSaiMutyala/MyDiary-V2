/**
 * One pictograph.
 *
 * Colour is inherited, so an icon takes on whatever the row, chip or heading around it is already
 * painted — which is the thing emoji could never do.
 *
 * @param {object} props
 * @param {string} props.name one of ICON_NAMES
 * @param {number} [props.size] in px; defaults to the surrounding text size
 */
export default function Icon({ name, size, sx, ...rest }) {
  // A stored emoji (a department's own icon) resolves to its name first, so screens can pass the
  // record straight through: <Icon name={dept.icon} />.
  const Glyph = ICONS[name] ?? ICONS[EMOJI_ICONS[name]];
  if (!Glyph) {
    // A missing name is a typo, not a reason to crash a page — it shows up as a gap in dev and the
    // guard test below catches it before it ships.
    if (import.meta.env?.DEV) console.warn(`<Icon name="${name}"> is not a known icon.`);
    return null;
  }
  return (
    <Glyph
      aria-hidden
      sx={{ fontSize: size ?? '1.15em', verticalAlign: '-0.18em', flexShrink: 0, ...sx }}
      {...rest}
    />
  );
}
